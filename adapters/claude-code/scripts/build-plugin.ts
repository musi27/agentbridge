// Bundles the plugin runtime (MCP server + hook) into self-contained ESM files under plugin/runtime/.
// The plugin is installed by copying its folder, so it cannot rely on node_modules. The bundles are committed;
// a test checks they match a fresh build. Usage: node scripts/build-plugin.ts
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { basename, dirname, join, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const RUNTIME_DIR = join(root, 'plugin', 'runtime');

/** Bundle in memory (the freshness test compares against the committed files). */
export async function bundlePlugin(): Promise<Map<string, string>> {
  const r = await build({
    write: false,
    absWorkingDir: root, // comments in the output name paths relative to this; keeps bytes independent of cwd
    entryPoints: { server: join(root, 'src', 'server-main.ts'), hook: join(root, 'src', 'hook-main.ts') },
    outdir: RUNTIME_DIR,
    outExtension: { '.js': '.mjs' },
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    conditions: ['agentbridge-source'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
    // CommonJS dependencies inside an ESM bundle need a real `require` for Node built-ins.
    banner: { js: "// Generated by adapters/claude-code/scripts/build-plugin.ts. Do not edit.\nimport { createRequire as __abCreateRequire } from 'node:module';\nconst require = __abCreateRequire(import.meta.url);" },
  });
  return new Map(r.outputFiles.map((f) => [basename(f.path), f.text]));
}

export async function buildPlugin(): Promise<void> {
  mkdirSync(RUNTIME_DIR, { recursive: true });
  for (const [name, text] of await bundlePlugin()) writeFileSync(join(RUNTIME_DIR, name), text);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildPlugin();
